"""Refresh assets/js/pubs.js from PubMed, CV-gated.

Usage:  python3 scripts/update_pubs.py [--cv PATH_TO_CV.docx]

Only papers whose title appears in Will's CV are published. Anything on PubMed
that matches the author search but is NOT in the CV is written to
scripts/pending_pubs.json for review in the weekly briefing (it is either a new
paper to add to the CV, or a different "W. Mair" to add to EXCLUDE).
Add PMIDs to FEATURED to show them on the home page.
"""
import json, pathlib, re, subprocess, sys, urllib.parse, urllib.request

EUTILS = "https://eutils.ncbi.nlm.nih.gov/entrez/eutils/"
QUERY = ('(Mair WB[Author]) OR (Mair W[Author] AND (Harvard[Affiliation] OR Dillin A[Author] '
         'OR Partridge L[Author] OR Salk[Affiliation] OR "University College London"[Affiliation]))')
# Papers by other authors named W. Mair, plus superseded preprints. Check new papers against the CV.
EXCLUDE = {
    "2865721",   # 1985 anaesthesia paper (different W.B. Mair)
    "39071403",  # 2024 bioRxiv preprint, later published in Life Sci Alliance
    "33188775",  # Tau PTM profiles, Cell 2020 (Waltraud Mair, Steen lab)
    "41616780",  # Molecular features of human pathological tau, Cell 2026 (Steen lab)
    "26877193",  # FLEXITau, Anal Chem 2016 (Steen lab)
    "27594585",  # Tau-A152T iPSC neurons, Stem Cell Reports 2016 (Haggarty lab)
}
FEATURED = ["42162381", "41270125", "29107506", "27919065", "25723162", "21331044", "31411562", "32905769", "37946042", "37721956", "39572679"]
OUT = pathlib.Path(__file__).resolve().parent.parent / "assets" / "js" / "pubs.js"
PENDING = pathlib.Path(__file__).resolve().parent / "pending_pubs.json"
DEFAULT_CV = pathlib.Path.home() / "Library/CloudStorage/OneDrive-HarvardUniversity/CV/Mair_CV_2026.docx"


def norm(text):
    return re.sub(r"\s+", " ", re.sub(r"[^a-z0-9 ]", " ", text.lower())).strip()


def cv_text():
    cv = pathlib.Path(sys.argv[sys.argv.index("--cv") + 1]) if "--cv" in sys.argv else DEFAULT_CV
    if not cv.exists():
        sys.exit(f"CV not found: {cv}  (pass --cv PATH)")
    txt = subprocess.run(["textutil", "-convert", "txt", "-stdout", str(cv)], capture_output=True, text=True).stdout
    return norm(txt)


def in_cv(title, cvn):
    w = norm(title).split()
    return any(" ".join(w[i:i + 5]) in cvn for i in range(max(1, len(w) - 4)))


def get(endpoint, **params):
    url = EUTILS + endpoint + "?" + urllib.parse.urlencode(dict(params, db="pubmed", retmode="json"))
    with urllib.request.urlopen(url, timeout=60) as r:
        return json.load(r)


ids = get("esearch.fcgi", term=QUERY, retmax=500)["esearchresult"]["idlist"]
ids += [f for f in FEATURED if f not in ids]
summary = get("esummary.fcgi", id=",".join(ids))["result"]

CVN = cv_text()
pubs, pending = [], []
for pmid in summary["uids"]:
    r = summary[pmid]
    if pmid in EXCLUDE or {"Erratum", "Published Erratum"} & set(r.get("pubtype", [])):  # commentaries are kept (they are in the CV)
        continue
    doi = next((a["value"] for a in r.get("articleids", []) if a["idtype"] == "doi"), "")
    types = r.get("pubtype", [])
    kind = "preprint" if r["source"] in ("bioRxiv", "medRxiv") or "Preprint" in types else (
        "review" if "Review" in types else "commentary" if {"Comment", "Editorial"} & set(types) else "article")
    entry = {
        "pmid": pmid,
        "year": int(r["pubdate"][:4]),
        "title": r["title"].rstrip("."),
        "authors": [a["name"] for a in r["authors"]],
        "journal": r["source"],
        "doi": doi,
        "kind": kind,
        "featured": pmid in FEATURED,
    }
    (pubs if in_cv(entry["title"], CVN) else pending).append(entry)

pubs.sort(key=lambda p: (-p["year"], p["title"]))
OUT.write_text("// Generated by scripts/update_pubs.py — do not edit by hand.\nwindow.PUBS = "
               + json.dumps(pubs, ensure_ascii=False, indent=1) + ";\n")
PENDING.write_text(json.dumps(pending, ensure_ascii=False, indent=1) + "\n")
print(f"Wrote {len(pubs)} publications (all in CV) to {OUT}")
print(f"{len(pending)} PubMed record(s) not in the CV -> {PENDING.name} for review")
for p in pending:
    print(f"  PENDING {p['pmid']} {p['year']} {p['journal']}: {p['title'][:90]} ({p['authors'][0]} ... {p['authors'][-1]})")
